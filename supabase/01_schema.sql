-- Este archivo reconstruye el esquema tal como lo usa index.html HOY,
-- y agrega columnas/tablas nuevas para las funciones pedidas.
--
-- ⚠ IMPORTANTE: tu base YA existe. NO ejecutes esto entero a ciegas.
--   1. Todo lo que crea tablas/columnas usa "IF NOT EXISTS" o
--      "ADD COLUMN IF NOT EXISTS": es seguro correrlo sobre la base actual.
--   2. Antes de aplicar, sacá una copia (Dashboard → Database → Backups,
--      o el botón "Descargar copia de seguridad" de la app).
--   3. Aplicá en este orden: 01_schema → 02_security → 03_rpc →
--      04_triggers → 05_views. Ver docs/MIGRATION.md.
